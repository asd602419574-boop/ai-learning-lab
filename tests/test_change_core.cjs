'use strict';
const assert=require('node:assert/strict');
const C=require('../learning/change-core.js');
const draft=C.empty();
assert.equal(C.check(draft).ready,false);
for(const key of C.FIELDS)draft.design[key]='自己的设计：'+key;
assert.equal(C.check(draft).ready,true);
assert.match(C.check(draft).scope,/结构/);
C.submit(draft);assert.equal(C.current(draft),true);
draft.design.impact='修订影响';assert.equal(C.current(draft),false);
draft.track='engineering';assert.equal(C.check(draft).ready,false);
const checks=C.REQUIRED.map(id=>({id,passed:true,feedback:'固定规则'}));
const report={format:'approval-change-evidence',version:1,passed:true,variant:false,source_hashes:{'service.py':'abc'},checks,requests:[],sql:[]};
C.attach(draft,report);assert.equal(C.check(draft).ready,false);
report.variant=true;C.attach(draft,report);assert.equal(C.check(draft).ready,true);
C.submit(draft);assert.equal(C.current(draft),true);
const restored=C.parse(JSON.stringify(draft));assert.deepEqual(restored,draft);
assert.throws(()=>C.parse('{"version":99}'));
const fake={...report,checks:[]};assert.throws(()=>C.attach(draft,fake));
assert.throws(()=>C.attach(draft,{...report,passed:false}));
const failed={...report,passed:false,checks:checks.map((c,i)=>i?c:{...c,passed:false})};
C.attach(draft,failed);assert.equal(C.current(draft),false);assert.equal(C.check(draft).ready,false);
assert.throws(()=>C.parse(JSON.stringify({...draft,extra:1})));
console.log('PASS change artifacts: separate routes, structural feedback, revision invalidation, report completeness, JSON restore and no mastery claims');
